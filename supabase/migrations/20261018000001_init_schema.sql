-- Tipe status transaksi.
do $$
begin
  if not exists (select 1 from pg_type where typname = 'transaction_status' and typnamespace = 'public'::regnamespace) then
    create type public.transaction_status as enum ('pending', 'approved', 'rejected');
  end if;
end
$$;

-- ---------------------------------------------------------------------------
-- categories
-- ---------------------------------------------------------------------------
create table if not exists public.categories (
  id          bigint generated by default as identity primary key,
  name        text not null unique,
  icon        text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- frames
-- Overlay frame = 1 PNG (image_path). Lubang foto = kolom `slots` (jsonb),
-- tiap item: { "x": int, "y": int, "w": int, "h": int } dalam piksel PNG asli.
-- ---------------------------------------------------------------------------
create table if not exists public.frames (
  id           bigint generated by default as identity primary key,
  name         text not null,
  slug         text not null unique,
  image_path   text,
  price        numeric(10, 2) not null default 0,
  used         bigint not null default 0,
  width        integer not null,
  height       integer not null,
  slots        jsonb not null default '[]'::jsonb,
  category_id  bigint references public.categories (id) on delete set null,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint frames_slots_is_array check (jsonb_typeof(slots) = 'array'),
  constraint frames_dimensions_positive check (width > 0 and height > 0)
);

-- ---------------------------------------------------------------------------
-- testimonials
-- ---------------------------------------------------------------------------
create table if not exists public.testimonials (
  id          bigint generated by default as identity primary key,
  rating      integer not null check (rating between 1 and 5),
  emoji       text,
  name        text default 'Anonymous',
  message     text,
  frame_id    bigint references public.frames (id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- transactions
-- order_id & amount diisi otomatis oleh trigger (lihat migrasi functions).
-- ---------------------------------------------------------------------------
create table if not exists public.transactions (
  id               bigint generated by default as identity primary key,
  order_id         text not null unique,
  frame_id         bigint not null references public.frames (id) on delete cascade,
  customer_name    text not null,
  whatsapp_number  text,
  payment_method   text not null check (payment_method in ('bank_transfer', 'qris')),
  amount           numeric(10, 2) not null default 0,
  payment_proof    text,
  status           public.transaction_status not null default 'pending',
  approved_at      timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- admins (terhubung ke auth.users)
-- ---------------------------------------------------------------------------
create table if not exists public.admins (
  id          uuid primary key references auth.users (id) on delete cascade,
  name        text not null,
  email       text not null unique,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Indeks
-- ---------------------------------------------------------------------------
create index if not exists frames_category_idx on public.frames (category_id);
create index if not exists frames_used_idx on public.frames (used desc);
create index if not exists testimonials_created_rating_idx on public.testimonials (created_at desc, rating);
create index if not exists transactions_status_idx on public.transactions (status);

-- ---------------------------------------------------------------------------
-- Trigger updated_at
-- ---------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists categories_set_updated_at on public.categories;
create trigger categories_set_updated_at
  before update on public.categories
  for each row execute function public.set_updated_at();

drop trigger if exists frames_set_updated_at on public.frames;
create trigger frames_set_updated_at
  before update on public.frames
  for each row execute function public.set_updated_at();

drop trigger if exists testimonials_set_updated_at on public.testimonials;
create trigger testimonials_set_updated_at
  before update on public.testimonials
  for each row execute function public.set_updated_at();

drop trigger if exists transactions_set_updated_at on public.transactions;
create trigger transactions_set_updated_at
  before update on public.transactions
  for each row execute function public.set_updated_at();
