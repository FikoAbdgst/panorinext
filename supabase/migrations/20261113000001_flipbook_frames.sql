-- =============================================================================
-- PanoriCam - Frame flipbook
-- Tabel overlay PNG khusus flipbook, terpisah dari `frames` (photostrip).
--
-- Satu baris `flipbook_frames` adalah satu overlay yang dipakai di seluruh
-- halaman flipbook. Satu sesi flipbook selalu berisi 10 halaman/frame.
-- `slots` tetap disediakan agar overlay bisa punya area foto tertentu; jika
-- kosong, foto halaman mengisi penuh area overlay.
-- =============================================================================

create table if not exists public.flipbook_frames (
  id          bigint generated by default as identity primary key,
  name        text not null,
  slug        text not null unique,
  image_path  text,
  width       integer not null default 1200,
  height      integer not null default 900,
  slots       jsonb not null default '[]'::jsonb,
  is_active   boolean not null default true,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint flipbook_frames_slots_is_array check (jsonb_typeof(slots) = 'array'),
  constraint flipbook_frames_dimensions_positive check (width > 0 and height > 0)
);

comment on table public.flipbook_frames is
  'Overlay PNG khusus flipbook; satu baris dipakai untuk seluruh halaman flipbook.';

comment on column public.flipbook_frames.slots is
  'Area foto opsional dalam piksel PNG asli: [{ "x": int, "y": int, "w": int, "h": int, "rotation"?: number }].';

drop trigger if exists flipbook_frames_set_updated_at on public.flipbook_frames;
create trigger flipbook_frames_set_updated_at
  before update on public.flipbook_frames
  for each row execute function public.set_updated_at();
