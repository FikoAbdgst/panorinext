-- =============================================================================
-- PanoriCam - Aset per tipe frame flipbook
--
-- Satu baris `flipbook_frames` sekarang menjadi satu TIPE frame flipbook.
-- Setiap tipe berisi 12 overlay PNG:
--   cover      : 1 sampul
--   page 1..10 : 10 halaman foto
--   back       : 1 penutup
--
-- Overlay disimpan terpisah agar admin bisa mengunggah/mengganti per halaman.
-- =============================================================================

create table if not exists public.flipbook_frame_assets (
  id          bigint generated by default as identity primary key,
  frame_id    bigint not null references public.flipbook_frames(id) on delete cascade,
  kind        text not null check (kind in ('cover', 'page', 'back')),
  page_index  integer not null default 0,
  image_path  text not null,
  width       integer not null default 1200,
  height      integer not null default 900,
  slots       jsonb not null default '[]'::jsonb,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint flipbook_frame_assets_kind_index check (
    (kind = 'page' and page_index between 1 and 10)
    or (kind in ('cover', 'back') and page_index = 0)
  ),
  constraint flipbook_frame_assets_unique unique (frame_id, kind, page_index),
  constraint flipbook_frame_assets_slots_is_array check (jsonb_typeof(slots) = 'array'),
  constraint flipbook_frame_assets_dimensions_positive check (width > 0 and height > 0)
);

comment on table public.flipbook_frame_assets is
  'Overlay PNG per halaman flipbook: 1 sampul, 10 halaman, 1 penutup untuk setiap tipe frame.';

create index if not exists flipbook_frame_assets_frame_id_idx
  on public.flipbook_frame_assets (frame_id);

drop trigger if exists flipbook_frame_assets_set_updated_at on public.flipbook_frame_assets;
create trigger flipbook_frame_assets_set_updated_at
  before update on public.flipbook_frame_assets
  for each row execute function public.set_updated_at();

alter table public.flipbook_frame_assets enable row level security;

drop policy if exists flipbook_frame_assets_select_public on public.flipbook_frame_assets;
create policy flipbook_frame_assets_select_public
  on public.flipbook_frame_assets for select
  to anon, authenticated
  using (
    exists (
      select 1
      from public.flipbook_frames f
      where f.id = flipbook_frame_assets.frame_id
        and f.is_active
    )
  );

drop policy if exists flipbook_frame_assets_admin_write on public.flipbook_frame_assets;
create policy flipbook_frame_assets_admin_write
  on public.flipbook_frame_assets for all
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- ---------------------------------------------------------------------------
-- Pindahkan overlay lama (satu PNG untuk semua halaman) menjadi 10 halaman.
-- Aman dijalankan berulang; baris yang sudah ada tidak ditimpa.
-- ---------------------------------------------------------------------------
insert into public.flipbook_frame_assets
  (frame_id, kind, page_index, image_path, width, height, slots)
select
  f.id,
  'page',
  page_no,
  f.image_path,
  f.width,
  f.height,
  f.slots
from public.flipbook_frames f
cross join generate_series(1, 10) as page_no
where f.image_path is not null
on conflict (frame_id, kind, page_index) do nothing;
