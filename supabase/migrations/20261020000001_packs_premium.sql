-- ---------------------------------------------------------------------------
-- set_transaction_defaults: amount dari pack atau frame lama.
-- ---------------------------------------------------------------------------
create or replace function public.set_transaction_defaults()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_price numeric(10, 2);
begin
  if num_nonnulls(new.frame_id, new.pack_id) <> 1 then
    raise exception 'Transaksi harus memiliki tepat satu frame atau pack';
  end if;

  if new.pack_id is not null then
    select p.price into v_price
    from public.packs p
    where p.id = new.pack_id
      and p.is_active = true;

    if v_price is null then
      raise exception 'Paket tidak ditemukan atau tidak aktif';
    end if;
  else
    select f.price into v_price
    from public.frames f
    where f.id = new.frame_id;

    if v_price is null then
      raise exception 'Frame tidak ditemukan';
    end if;
  end if;

  new.amount := v_price;
  new.status := 'pending';
  new.approved_at := null;

  loop
    new.order_id :=
      'ORD'
      || to_char(now(), 'YYYYMMDD')
      || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6));
    exit when not exists (
      select 1 from public.transactions t where t.order_id = new.order_id
    );
  end loop;

  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- generate_premium_code(): 8 karakter, tanpa huruf/angka ambigu.
-- ---------------------------------------------------------------------------
create or replace function public.generate_premium_code()
returns text
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
  v_alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  v_code text;
  v_index integer;
begin
  loop
    v_code := '';
    for i in 1..8 loop
      v_index := 1 + floor(random() * length(v_alphabet))::integer;
      v_code := v_code || substr(v_alphabet, v_index, 1);
    end loop;

    exit when not exists (
      select 1 from public.premium_access a where a.code = v_code
    );
  end loop;

  return v_code;
end;
$$;

-- ---------------------------------------------------------------------------
-- approve_transaction_with_code(): approve + buat kode secara atomik.
-- Transaksi frame lama tidak dibuatkan kode (kompatibilitas).
-- ---------------------------------------------------------------------------
create or replace function public.approve_transaction_with_code(p_transaction_id bigint)
returns table (
  access_id bigint,
  room_code text,
  pack_id bigint,
  pack_name text,
  first_used_at timestamptz,
  expires_at timestamptz,
  revoked_at timestamptz
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_transaction public.transactions%rowtype;
  v_access public.premium_access%rowtype;
  v_pack_name text;
begin
  select * into v_transaction
  from public.transactions t
  where t.id = p_transaction_id
  for update;

  if not found then
    raise exception 'Transaksi tidak ditemukan';
  end if;

  if v_transaction.status = 'rejected' then
    raise exception 'Transaksi sudah ditolak';
  end if;

  update public.transactions
  set status = 'approved',
      approved_at = coalesce(approved_at, now())
  where id = p_transaction_id;

  if v_transaction.pack_id is null then
    return;
  end if;

  select * into v_access
  from public.premium_access a
  where a.transaction_id = p_transaction_id;

  if not found then
    insert into public.premium_access (
      transaction_id,
      pack_id,
      code,
      customer_name,
      whatsapp_number
    )
    values (
      p_transaction_id,
      v_transaction.pack_id,
      public.generate_premium_code(),
      v_transaction.customer_name,
      v_transaction.whatsapp_number
    )
    returning * into v_access;
  end if;

  select p.name into v_pack_name
  from public.packs p
  where p.id = v_access.pack_id;

  return query
    select
      v_access.id,
      v_access.code,
      v_access.pack_id,
      v_pack_name,
      v_access.first_used_at,
      v_access.expires_at,
      v_access.revoked_at;
end;
$$;

-- ---------------------------------------------------------------------------
-- redeem_premium_code(): mulai masa aktif sekali, kembalikan token sesi.
-- ---------------------------------------------------------------------------
create or replace function public.redeem_premium_code(p_code text)
returns table (
  access_id bigint,
  pack_id bigint,
  pack_name text,
  room_code text,
  first_used_at timestamptz,
  expires_at timestamptz,
  session_token uuid
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_access public.premium_access%rowtype;
  v_pack public.packs%rowtype;
  v_normalized text;
begin
  v_normalized := upper(regexp_replace(coalesce(p_code, ''), '[^A-Za-z0-9]', '', 'g'));

  if length(v_normalized) <> 8 then
    return;
  end if;

  select * into v_access
  from public.premium_access a
  where a.code = v_normalized
  for update;

  if not found or v_access.revoked_at is not null then
    return;
  end if;

  select * into v_pack
  from public.packs p
  where p.id = v_access.pack_id
    and p.is_active = true;

  if not found then
    return;
  end if;

  if v_access.first_used_at is null then
    update public.premium_access
    set first_used_at = now(),
        expires_at = now() + make_interval(days => v_pack.duration_days),
        session_token = coalesce(session_token, gen_random_uuid())
    where id = v_access.id
    returning * into v_access;
  elsif v_access.expires_at is null or v_access.expires_at <= now() then
    return;
  elsif v_access.session_token is null then
    update public.premium_access
    set session_token = gen_random_uuid()
    where id = v_access.id
    returning * into v_access;
  end if;

  return query
    select
      v_access.id,
      v_access.pack_id,
      v_pack.name,
      v_access.code,
      v_access.first_used_at,
      v_access.expires_at,
      v_access.session_token;
end;
$$;

