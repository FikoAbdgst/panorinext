-- ---------------------------------------------------------------------------
-- frames.access_type
-- ---------------------------------------------------------------------------
do $$
begin
  if not exists (
    select 1
    from pg_type
    where typname = 'frame_access_type'
      and typnamespace = 'public'::regnamespace
  ) then
    create type public.frame_access_type as enum ('free', 'premium');
  end if;
end
$$;

alter table public.frames
  add column if not exists access_type public.frame_access_type not null default 'free';

update public.frames
set access_type = 'premium'
where price > 0
  and access_type = 'free';

create index if not exists frames_access_type_idx on public.frames (access_type);

-- ---------------------------------------------------------------------------
-- packs
-- ---------------------------------------------------------------------------
create table if not exists public.packs (
  id            bigint generated by default as identity primary key,
  name          text not null,
  slug          text not null unique,
  description   text,
  price         numeric(10, 2) not null default 0,
  duration_days integer not null default 1,
  is_active     boolean not null default true,
  sort_order    integer not null default 0,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint packs_price_non_negative check (price >= 0),
  constraint packs_duration_positive check (duration_days > 0)
);

alter table public.packs enable row level security;

-- ---------------------------------------------------------------------------
-- pack_frames
-- ---------------------------------------------------------------------------
create table if not exists public.pack_frames (
  pack_id    bigint not null references public.packs (id) on delete cascade,
  frame_id   bigint not null references public.frames (id) on delete restrict,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  primary key (pack_id, frame_id)
);

alter table public.pack_frames enable row level security;

create index if not exists pack_frames_frame_idx on public.pack_frames (frame_id);

-- ---------------------------------------------------------------------------
-- premium_access
-- Satu kode untuk satu transaksi/pembelian (transaction_id unik).
-- Kode bisa juga dibuat manual oleh admin (transaction_id null).
-- Masa aktif dihitung saat kode pertama kali dipakai.
-- ---------------------------------------------------------------------------
create table if not exists public.premium_access (
  id              bigint generated by default as identity primary key,
  transaction_id  bigint unique references public.transactions (id) on delete set null,
  pack_id         bigint not null references public.packs (id) on delete restrict,
  code            text not null unique,
  customer_name   text,
  whatsapp_number text,
  first_used_at   timestamptz,
  expires_at      timestamptz,
  session_token   uuid unique,
  revoked_at      timestamptz,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  constraint premium_access_code_format check (code ~ '^[A-Z0-9]{8}$'),
  constraint premium_access_usage_complete check (
    (first_used_at is null and expires_at is null)
    or (first_used_at is not null and expires_at is not null)
  )
);

alter table public.premium_access enable row level security;

create index if not exists premium_access_pack_idx on public.premium_access (pack_id);
create index if not exists premium_access_expires_idx on public.premium_access (expires_at);
create index if not exists premium_access_token_idx on public.premium_access (session_token);

-- ---------------------------------------------------------------------------
-- transactions: dukung pack_id, frame_id lama tetap ada untuk kompatibilitas.
-- ---------------------------------------------------------------------------
alter table public.transactions
  add column if not exists pack_id bigint references public.packs (id) on delete restrict;

alter table public.transactions
  alter column frame_id drop not null;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'transactions_item_required'
      and conrelid = 'public.transactions'::regclass
  ) then
    alter table public.transactions
      add constraint transactions_item_required
      check (num_nonnulls(frame_id, pack_id) = 1);
  end if;
end
$$;

create index if not exists transactions_pack_idx on public.transactions (pack_id);

