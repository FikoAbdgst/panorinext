-- Hak eksekusi
-- ---------------------------------------------------------------------------
revoke all on function public.generate_premium_code() from public;
revoke all on function public.approve_transaction_with_code(bigint) from public;
revoke all on function public.redeem_premium_code(text) from public;

grant execute on function public.approve_transaction_with_code(bigint) to service_role;
grant execute on function public.redeem_premium_code(text) to service_role;
